"""Generate app/src/commonTest/resources-free golden fixtures for the Kotlin Maia-3 encoder.

Writes a Kotlin source file holding, per case: the non-zero token indices the reference Python
encoder (maia3.dataset) produces, the legal-move vocabulary indices, and the reference model's top
moves at three ratings. The Kotlin encoder test compares against the first two everywhere (no model
needed); the desktop ONNX test compares against the third when a model file is available.

Also asserts the exported ONNX agrees with the *unpatched* PyTorch model, so the fixture doubles as
the conversion parity check.

Usage:
    PYTHONPATH=/path/to/maia3-clone python make_golden.py maia3-5m.pt maia3-5m.onnx Out.kt
"""

import sys
from collections import deque
from types import SimpleNamespace

import chess
import numpy as np
import onnxruntime as ort
import torch

import maia3.models as models
from maia3.dataset import get_historical_tokens, get_legal_moves_mask, tokenize_board
from maia3.model_registry import resolve_model_spec
from maia3.utils import get_all_possible_moves, mirror_move

RATINGS = (1100, 1500, 1900)
TOP = 5

# (name, start fen, moves played from it). The prediction is for the position after the moves, with
# every intermediate position as history, mirroring maia3-uci --use-uci-history.
CASES = [
    ("startpos", chess.STARTING_FEN, []),
    ("italian_black_to_move", "r1bqkbnr/pppp1ppp/2n5/4p3/2B1P3/5N2/PPPP1PPP/RNBQK2R b KQkq - 4 4", []),
    ("italian_with_history", chess.STARTING_FEN, ["e2e4", "e7e5", "g1f3", "b8c6", "f1c4"]),
    ("sicilian_history_white_to_move", chess.STARTING_FEN,
     ["e2e4", "c7c5", "g1f3", "d7d6", "d2d4", "c5d4", "f3d4", "g8f6", "b1c3", "a7a6"]),
    ("en_passant_available", "rnbqkbnr/ppp1p1pp/8/3pPp2/8/8/PPPP1PPP/RNBQKBNR w KQkq f6 0 3", []),
    ("white_promotes", "8/4P1k1/8/8/8/8/6K1/8 w - - 0 1", []),
    ("black_promotes", "8/6K1/8/8/8/8/2p1k3/8 b - - 0 1", []),
    ("black_castles", "r3k2r/pppq1ppp/2npbn2/2b1p3/2B1P3/2NPBN2/PPPQ1PPP/R3K2R b KQkq - 6 8", []),
]


def reference_model(checkpoint_path):
    spec = resolve_model_spec("maia3-5m")
    cfg = SimpleNamespace(**spec.config, device="cpu")
    model = models.MAIA3Model(cfg)
    state = torch.load(checkpoint_path, map_location="cpu", weights_only=True)
    state = state.get("model_state_dict", state)
    model.load_state_dict({k.replace("smolgen", "gab"): v for k, v in state.items()}, strict=True)
    model.eval()
    return model, cfg


def main(checkpoint_path, onnx_path, out_path):
    model, cfg = reference_model(checkpoint_path)
    session = ort.InferenceSession(onnx_path, providers=["CPUExecutionProvider"])
    vocab = get_all_possible_moves()
    vocab_index = {m: i for i, m in enumerate(vocab)}

    lines = [
        "// GENERATED by tools/maia3/make_golden.py from the maia3-5m checkpoint. Do not edit.",
        "package com.example.myapplication.explorer",
        "",
        "internal object MaiaGolden {",
        "    class Case(",
        "        val name: String,",
        "        val startFen: String,",
        "        val moves: List<String>,",
        "        val tokenIndices: IntArray,",
        "        val legalIndices: IntArray,",
        "        val top: Map<Int, List<Pair<String, Double>>>,",
        "    )",
        "",
        "    val cases = listOf(",
    ]
    max_diff = 0.0
    for name, fen, moves in CASES:
        board = chess.Board(fen)
        history = deque([tokenize_board(board)], maxlen=cfg.history)
        for uci in moves:
            board.push(chess.Move.from_uci(uci))
            history.append(tokenize_board(board))
        tokens = get_historical_tokens(history, cfg, 0.0, 0.0, 0.0, 0.0)
        flat = tokens.reshape(-1).numpy()
        token_indices = np.nonzero(flat)[0].tolist()
        mask = get_legal_moves_mask(board, vocab_index)
        legal_indices = torch.nonzero(mask).reshape(-1).tolist()

        top = {}
        for rating in RATINGS:
            elo = torch.tensor([rating], dtype=torch.long)
            with torch.no_grad():
                logits, _, _ = model(tokens.unsqueeze(0), elo, elo)
            onnx_logits = session.run(
                ["logits_move"],
                {"tokens": tokens.unsqueeze(0).numpy(), "self_elo": elo.numpy(), "oppo_elo": elo.numpy()},
            )[0]
            max_diff = max(max_diff, float(np.abs(onnx_logits - logits.numpy()).max()))
            masked = logits[0].masked_fill(~mask, float("-inf"))
            probs = torch.softmax(masked, dim=-1)
            values, indices = torch.topk(probs, k=min(TOP, len(legal_indices)))
            picks = []
            for p, i in zip(values.tolist(), indices.tolist()):
                uci = vocab[i] if board.turn == chess.WHITE else mirror_move(vocab[i])
                picks.append((uci, p))
            top[rating] = picks

        def ints(values):
            return "intArrayOf(" + ", ".join(str(v) for v in values) + ")"

        moves_kt = "listOf(" + ", ".join(f'"{m}"' for m in moves) + ")"
        top_kt = ", ".join(
            f"{r} to listOf(" + ", ".join(f'"{u}" to {p:.6f}' for u, p in picks) + ")"
            for r, picks in top.items()
        )
        lines += [
            "        Case(",
            f'            name = "{name}",',
            f'            startFen = "{fen}",',
            f"            moves = {moves_kt},",
            f"            tokenIndices = {ints(token_indices)},",
            f"            legalIndices = {ints(legal_indices)},",
            f"            top = mapOf({top_kt}),",
            "        ),",
        ]
    lines += ["    )", "}", ""]
    if max_diff > 1e-3:
        raise SystemExit(f"ONNX disagrees with PyTorch: max abs logit diff {max_diff}")
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out_path}; max abs ONNX-vs-PyTorch logit diff {max_diff:.2e}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3])
